#!/bin/sh
# Push the server config in build/ to the linode, or show how the box drifted from it.
#
# Usage: build/deploy.sh [push|diff] [nginx|search|vehicles|lachliste|geomaxing|monitor|all]
#        (defaults: push, all; a lone target means push, e.g. `build/deploy.sh nginx`)
#
# push  only touches what differs from the box; set FORCE=1 to push + restart anyway.
# diff  read-only: prints the diff between the repo and the files on the box.
set -eu

cd "$(dirname "$0")"
host=linode
stamp=$(date +%Y%m%d%H%M%S)
keep=5   # old nginx.conf.bak-* files to keep on the box
game_scripts="${GAME_SCRIPTS:-$HOME/repos/game/scripts}"

ALL="search vehicles lachliste geomaxing monitor nginx"

# target -> init script name
svc_of() {
	case "$1" in
		search) echo ftlm-search-server ;;
		vehicles) echo ftlm-vehicles-server ;;
		lachliste|geomaxing) echo "$1" ;;
		*) echo "unknown service target: $1" >&2; exit 2 ;;
	esac
}

is_janoshi() { [ "$1" = lachliste ] || [ "$1" = geomaxing ]; }

# true if the repo file differs from (or is missing on) the box
differs() {
	local_file="$1"; remote_file="$2"
	! ssh "$host" "cat $remote_file" 2>/dev/null | cmp -s - "$local_file"
}

show_diff() {
	local_file="$1"; remote_file="$2"
	if ssh "$host" "cat $remote_file" 2>/dev/null | diff -u --label "box:$remote_file" --label "repo:$local_file" - "$local_file"; then
		echo "ok      $remote_file"
	fi
}

# ---- conf.d for the janoshi apps (holds the DB password: never print it) ----

janoshi_env() {
	app="$1"
	env_file="$game_scripts/$app/deploy.env"
	[ -f "$env_file" ] || { echo "missing $env_file" >&2; exit 1; }
	(
		. "$env_file"
		[ -f "$game_scripts/$app/deploy.local.env" ] && . "$game_scripts/$app/deploy.local.env"
		printf '# Generated by faster-than-light-memes/build/deploy.sh from game/scripts/%s/deploy.env\n' "$app"
		printf "export PORT='%s' DB_HOST='%s' DB_PORT='%s' DB_NAME='%s' DB_USER='%s' DB_PASSWORD='%s'\n" \
			"$APP_PORT" "$DB_HOST" "$DB_PORT" "$DB_NAME" "$DB_USER" "$DB_PASSWORD"
	)
}

# ---- diff ----

diff_target() {
	t="$1"
	case "$t" in
		nginx) show_diff nginx/nginx.conf /etc/nginx/nginx.conf ;;
		monitor)
			show_diff monitor/collect.py /usr/local/bin/ftlm-collect
			show_diff monitor/index.html /var/www/ftlm-status/index.html
			ssh "$host" "crontab -l | grep -qF '$cron_line'" && echo "ok      cron entry" || echo "MISSING cron entry"
			;;
		*)
			svc=$(svc_of "$t")
			show_diff "openrc/$svc" "/etc/init.d/$svc"
			if is_janoshi "$t"; then
				if janoshi_env "$t" | ssh "$host" "cmp -s - /etc/conf.d/$t"; then
					echo "ok      /etc/conf.d/$t"
				else
					echo "DIFFERS /etc/conf.d/$t (contents not shown, it holds a secret)"
				fi
			fi
			;;
	esac
}

# ---- monitor (health + traffic collector and its dashboard, see monitor/) ----

cron_line='* * * * * /usr/local/bin/ftlm-collect >> /var/log/ftlm-collect.log 2>&1'

# Login for /admin/. Created once; the password is hashed on the box, never stored here.
ensure_admin_login() {
	ssh "$host" 'test -s /etc/nginx/.htpasswd_admin' && return
	user="${ADMIN_USER:-admin}"
	pw="${ADMIN_PASSWORD:-}"
	if [ -z "$pw" ]; then
		printf 'Password for /admin/ (user %s): ' "$user" >&2
		stty -echo; read -r pw; stty echo; echo >&2
	fi
	[ -n "$pw" ] || { echo "empty password" >&2; exit 1; }
	hash=$(printf '%s\n' "$pw" | ssh "$host" 'openssl passwd -apr1 -stdin')
	printf '%s:%s\n' "$user" "$hash" | ssh "$host" 'umask 037 && cat > /etc/nginx/.htpasswd_admin && chgrp nginx /etc/nginx/.htpasswd_admin'
	echo "created /etc/nginx/.htpasswd_admin (user $user)"
}

push_monitor() {
	if [ -z "${FORCE:-}" ] && ! differs monitor/collect.py /usr/local/bin/ftlm-collect \
		&& ! differs monitor/index.html /var/www/ftlm-status/index.html \
		&& ssh "$host" "crontab -l | grep -qF '$cron_line' && test -s /etc/nginx/.htpasswd_admin"; then
		echo "ok      monitor (unchanged)"; return
	fi
	ensure_admin_login
	ssh "$host" 'mkdir -p /var/www/ftlm-status && install -d -m 700 /var/lib/ftlm-monitor'
	scp -q monitor/collect.py "$host:/usr/local/bin/ftlm-collect"
	scp -q monitor/index.html "$host:/var/www/ftlm-status/index.html"
	ssh "$host" "chmod 755 /usr/local/bin/ftlm-collect /var/www/ftlm-status/index.html \
		&& (crontab -l | grep -vF ftlm-collect; echo '$cron_line') | crontab -"
	# First install: seed the stats from the existing access.log (one-off, can take a minute).
	ssh "$host" '[ -f /var/lib/ftlm-monitor/state.json ] || /usr/local/bin/ftlm-collect --backfill'
	ssh "$host" '/usr/local/bin/ftlm-collect'
	echo "pushed  monitor"
}

# ---- push ----

push_nginx() {
	if [ -z "${FORCE:-}" ] && ! differs nginx/nginx.conf /etc/nginx/nginx.conf; then
		echo "ok      nginx (unchanged)"; return
	fi
	ssh "$host" "cp /etc/nginx/nginx.conf /etc/nginx/nginx.conf.bak-$stamp"
	scp -q nginx/nginx.conf "$host:/etc/nginx/nginx.conf"
	if ! ssh "$host" 'nginx -t'; then
		ssh "$host" "cp /etc/nginx/nginx.conf.bak-$stamp /etc/nginx/nginx.conf"
		echo "nginx -t failed, restored previous config" >&2
		exit 1
	fi
	ssh "$host" 'rc-service nginx reload'
	# prune: keep the newest $keep backups
	ssh "$host" "ls -1t /etc/nginx/nginx.conf.bak-* 2>/dev/null | tail -n +$((keep + 1)) | xargs -r rm -f"
	echo "pushed  nginx"
}

push_service() {
	t="$1"
	svc=$(svc_of "$t")
	changed=
	if is_janoshi "$t"; then
		# Stop a copy started by hand with the old start.sh, so the port is free.
		if [ -n "${FORCE:-}" ] || ! janoshi_env "$t" | ssh "$host" "cmp -s - /etc/conf.d/$t"; then
			janoshi_env "$t" | ssh "$host" "umask 077 && cat > /etc/conf.d/$t"
			changed=1
		fi
	fi
	if [ -n "${FORCE:-}" ] || differs "openrc/$svc" "/etc/init.d/$svc"; then
		ssh "$host" "[ -f /etc/init.d/$svc ] && cp /etc/init.d/$svc /etc/init.d/$svc.bak || true"
		scp -q "openrc/$svc" "$host:/etc/init.d/$svc"
		changed=1
	fi
	if [ -z "$changed" ]; then
		echo "ok      $svc (unchanged)"; return
	fi
	if is_janoshi "$t"; then
		ssh "$host" "[ -f /opt/$t/run/app.pid ] && kill \$(cat /opt/$t/run/app.pid) 2>/dev/null; rm -f /opt/$t/run/app.pid; true"
	fi
	ssh "$host" "chmod 755 /etc/init.d/$svc && rc-update add $svc default >/dev/null && rc-service $svc restart"
	echo "pushed  $svc"
}

push_target() {
	case "$1" in
		nginx) push_nginx ;;
		monitor) push_monitor ;;
		*) push_service "$1" ;;
	esac
}

# ---- main ----

cmd=push
case "${1:-}" in
	push|diff) cmd="$1"; shift ;;
esac
target="${1:-all}"

[ "$target" = all ] && target="$ALL"

for t in $target; do
	case "$t" in
		nginx|search|vehicles|lachliste|geomaxing|monitor) ;;
		*) echo "usage: $0 [push|diff] [nginx|search|vehicles|lachliste|geomaxing|monitor|all]" >&2; exit 2 ;;
	esac
done

for t in $target; do
	"${cmd}_target" "$t"
done
