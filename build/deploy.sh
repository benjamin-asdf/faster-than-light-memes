#!/bin/sh
# Push the server config in build/ to the linode and reload what changed.
# Usage: build/deploy.sh [nginx|search|vehicles|lachliste|geomaxing|all]   (default: all)
set -eu

cd "$(dirname "$0")"
host=linode
what="${1:-all}"
stamp=$(date +%Y%m%d%H%M%S)

deploy_nginx() {
	ssh "$host" "cp /etc/nginx/nginx.conf /etc/nginx/nginx.conf.bak-$stamp"
	scp nginx/nginx.conf "$host:/etc/nginx/nginx.conf"
	if ! ssh "$host" 'nginx -t'; then
		ssh "$host" "cp /etc/nginx/nginx.conf.bak-$stamp /etc/nginx/nginx.conf"
		echo "nginx -t failed, restored previous config" >&2
		exit 1
	fi
	ssh "$host" 'rc-service nginx reload'
}

deploy_service() {
	svc="$1"
	scp "openrc/$svc" "$host:/etc/init.d/$svc"
	ssh "$host" "chmod 755 /etc/init.d/$svc && rc-update add $svc default && rc-service $svc restart"
}

# The janoshi apps (lachliste, geomaxing) take their env from the game repo's
# deploy.env, which holds the DB password. Write it to /etc/conf.d/<app>, root-only.
game_scripts="${GAME_SCRIPTS:-$HOME/repos/game/scripts}"

deploy_janoshi() {
	app="$1"
	env_file="$game_scripts/$app/deploy.env"
	[ -f "$env_file" ] || { echo "missing $env_file" >&2; exit 1; }
	(
		. "$env_file"
		[ -f "$game_scripts/$app/deploy.local.env" ] && . "$game_scripts/$app/deploy.local.env"
		printf '# Generated by faster-than-light-memes/build/deploy.sh from game/scripts/%s/deploy.env\n' "$app"
		printf "export PORT='%s' DB_HOST='%s' DB_PORT='%s' DB_NAME='%s' DB_USER='%s' DB_PASSWORD='%s'\n" \
			"$APP_PORT" "$DB_HOST" "$DB_PORT" "$DB_NAME" "$DB_USER" "$DB_PASSWORD"
	) | ssh "$host" "umask 077 && cat > /etc/conf.d/$app"
	# Stop a copy started by hand with the old start.sh, so the port is free.
	ssh "$host" "[ -f /opt/$app/run/app.pid ] && kill \$(cat /opt/$app/run/app.pid) 2>/dev/null; rm -f /opt/$app/run/app.pid; true"
	deploy_service "$app"
}

case "$what" in
	nginx) deploy_nginx ;;
	search) deploy_service ftlm-search-server ;;
	vehicles) deploy_service ftlm-vehicles-server ;;
	lachliste|geomaxing) deploy_janoshi "$what" ;;
	all)
		deploy_service ftlm-search-server
		deploy_service ftlm-vehicles-server
		deploy_janoshi lachliste
		deploy_janoshi geomaxing
		deploy_nginx
		;;
	*) echo "usage: $0 [nginx|search|vehicles|lachliste|geomaxing|all]" >&2; exit 2 ;;
esac
